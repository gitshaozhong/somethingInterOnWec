/** 所有城市扁平列表 */
export const ALL_CITIES: string[] = PROVINCES.reduce<string[]>((acc, p) => acc.concat(p.cities), []);

/** 城市名 → 拼音首字母（未匹配归 "#"） */
export function getCityInitial(city: string): string {
  return CITY_PINYIN[city] || "#";
}

/**
 * 构建按首字母分组的城市索引
 * 返回：[{ letter: "B", cities: ["北京", "保定", ...] }, ...]，按字母顺序排序，无城市的字母不返回
 */
export function buildCityIndex(): Array<{ letter: string; cities: string[] }> {
  const groups: Record<string, string[]> = {};
  for (const city of ALL_CITIES) {
    const letter = getCityInitial(city);
    if (!groups[letter]) groups[letter] = [];
    groups[letter].push(city);
  }
  return Object.keys(groups)
    .sort((a, b) => {
      // 字母在前，"#" 在最后
      if (a === "#") return 1;
      if (b === "#") return -1;
      return a.localeCompare(b);
    })
    .map((letter) => ({ letter, cities: groups[letter].sort((x, y) => x.localeCompare(y)) }));
}
